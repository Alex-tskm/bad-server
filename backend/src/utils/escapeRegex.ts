/**
 * Экранирует специальные символы в строке для безопасного использования в регулярных выражениях.
 * @param value - входная строка, в которой нужно экранировать спецсимволы
 * @returns строка, где все специальные символы регулярных выражений предварены обратным слешем
 */
export const escapeRegex = (value: string) =>
    // Заменяем все специальные символы регулярных выражений на их экранированные версии
    value.replace(
        // Регулярное выражение, которое ищет все спецсимволы, имеющие особое значение в RegExp:
        // . * + ? ^ $ { } ( ) | [ ] \ — эти символы влияют на логику работы регулярных выражений
        /[.*+?^${}()|[\]\\]/g,
        // Для каждого найденного символа: $& означает сам совпавший символ,
        // а префикс \ экранирует его — в результате . становится \., * становится \* и т. д.
        '\\$&'
    );
